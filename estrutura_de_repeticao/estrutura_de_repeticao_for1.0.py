### Estrutura de repetição: for
#for é uma instrutura de repetição baseada em contagem

for item in range(2, 9, 3): #item é a variavel que vamos utilizar para implementar
    print(item)



####explicação do código:
#for é uma instrutura de repetição baseada em contagem
#item é a variavel que vamos utilizar para implementar
#(2 é o valor inicial / 9 é o valor final / 3 é o passo)
