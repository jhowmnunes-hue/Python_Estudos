### Estrutura de repetição: for
#for é uma instrutura de repetição baseada em contagem

nomes = ["Laura", "Lis", "Guilherme", "Enzo", "Arthur"]
for nome in nomes:
    print(nome)

####explicação do código:
#O for vai ler o nome (nome da variavel), ele lê o primeiro nome e imprime, le o segundo nome da sequencia e imprime
#como se estivesse lendo um vetor de nomes
#É o mais proximo que conseguimos encontrar em outras linguagens de programação
