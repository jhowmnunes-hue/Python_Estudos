### Estrutura de repetição: for
#for é uma instrutura de repetição baseada em contagem

nome = input("Entre com seu nome: ")
for letra in nome:
    print(letra)

####explicação do código:
#for é uma instrutura de repetição baseada em contagem
#letra é a variavel que vamos utilizar para implementar
#Ao digitar o nome ele trata uma string com uma sequencia de letras. (a cada loop ele vai ler uma letra do nome, imprimindo na vertical)
