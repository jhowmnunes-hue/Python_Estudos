# range
for item in range(5): #imprime de 1 a 4 ( 0, 1, 2, 3, 4) lembrando que o python considera o zero
    print(item)

for item in range(20,25): # imprime do 20, 21, 22, 23, 24
    print(item)

for item in range(100, 150, 10): #Imprime de 100 a 150 de 10 em 10 por conta do passo
    print(item)